// Activity: usage stats, weekday bar chart and ✨ AI Insight (§6.2).
import { ScrollView, StyleSheet, View } from 'react-native';
import { ActivityIndicator, Card, IconButton, List, Text, useTheme } from 'react-native-paper';
import { StatBar, StatTile } from '../src/components/StatBar';
import { ErrorState, SkeletonList } from '../src/components/States';
import { useCurrentUser } from '../src/hooks/useAuth';
import { useStats } from '../src/hooks/useStats';
import { RADIUS, SPACING, STATUS } from '../src/theme';
import { formatRange } from '../src/utils/time';

export default function Activity() {
  const user = useCurrentUser();
  const theme = useTheme();
  const { data, loading, error, reload, insight, insightIsAI, insightLoading, refreshInsight } = useStats(user.id);

  if (loading) return <View style={{ padding: SPACING.md }}><SkeletonList count={5} /></View>;
  if (error || !data) return <ErrorState message={error ?? 'No data'} onRetry={reload} />;
  const s = data.stats;
  const maxDay = Math.max(...s.byWeekday.map((d) => d.count), 1);

  return (
    <ScrollView contentContainerStyle={{ padding: SPACING.md, paddingBottom: SPACING.xl }}>
      <Card style={[styles.card, { backgroundColor: theme.colors.primaryContainer }]}>
        <Card.Title
          title={insightIsAI ? '✨ AI Insight' : '✨ Insight'}
          subtitle={insightIsAI ? 'Generated by Gemini from your anonymous stats' : 'Offline summary (AI unavailable)'}
          right={() => <IconButton icon="refresh" onPress={refreshInsight} disabled={insightLoading} accessibilityLabel="Refresh insight" />}
        />
        <Card.Content>
          {insightLoading ? <ActivityIndicator style={{ alignSelf: 'flex-start' }} /> : <Text variant="bodyLarge">{insight}</Text>}
        </Card.Content>
      </Card>

      <View style={styles.tiles}>
        <StatTile label="Total" value={s.total} />
        <StatTile label="Upcoming" value={s.upcoming} color={STATUS.available} />
        <StatTile label="Completed" value={s.completed} color={STATUS.past} />
        <StatTile label="Cancelled" value={s.cancelled} color={STATUS.booked} />
      </View>

      <Card style={styles.card}>
        <List.Item title={s.mostUsedRoom ?? '–'} description="Most used space" left={(p) => <List.Icon {...p} icon="star-outline" />} />
        <List.Item title={s.preferredWindow ? formatRange(s.preferredWindow.startMin, s.preferredWindow.endMin) : '–'} description="Preferred time window" left={(p) => <List.Icon {...p} icon="clock-outline" />} />
        <List.Item title={s.favouriteDay ?? '–'} description="Favourite day" left={(p) => <List.Icon {...p} icon="calendar-star" />} />
        <List.Item title={`${s.hoursThisMonth} h`} description="Hours booked this month" left={(p) => <List.Icon {...p} icon="timer-sand" />} />
      </Card>

      <Card style={styles.card}>
        <Card.Title title="Bookings by weekday" />
        <Card.Content>
          {s.byWeekday.map((d) => <StatBar key={d.day} label={d.day} value={d.count} max={maxDay} />)}
        </Card.Content>
      </Card>
    </ScrollView>
  );
}

const styles = StyleSheet.create({
  card: { borderRadius: RADIUS, marginBottom: SPACING.md },
  tiles: { flexDirection: 'row', flexWrap: 'wrap', gap: SPACING.sm + 4, marginBottom: SPACING.md },
});
